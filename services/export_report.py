"""Court-ready evidence export with SHA-256 hash chain."""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from typing import Any
from uuid import uuid4


def _sha256(data: str) -> str:
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def generate_report(
    investigation_id: str,
    query: str,
    result: dict[str, Any],
    reviewer: str = "investigator",
    reviews: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    generated_at = datetime.now(timezone.utc).isoformat()
    report_id = str(uuid4())

    payload = {
        "report_id": report_id,
        "investigation_id": investigation_id,
        "generated_at": generated_at,
        "query": query,
        "reviewer": reviewer,
        "classification": "LAW ENFORCEMENT SENSITIVE",
        "tools_executed": [
            {"tool": t.get("tool"), "success": t.get("success"), "time_ms": t.get("execution_time_ms")}
            for t in result.get("tool_results", [])
        ],
        "fusion_score": result.get("fusion", {}).get("fusion_score"),
        "correlation_clusters": result.get("correlation", {}).get("clusters", []),
        "graph_summary": {
            "node_count": result.get("graph", {}).get("node_count", 0),
            "edge_count": result.get("graph", {}).get("edge_count", 0),
            "suspicious_networks": result.get("graph", {}).get("suspicious_networks", []),
        },
        "human_reviews": reviews or [],
        "evidence_hash_chain": [],
    }

    canonical = json.dumps(payload, sort_keys=True, default=str)
    evidence_hash = _sha256(canonical)
    payload["evidence_hash_chain"] = [
        {"step": "report_canonicalization", "algorithm": "SHA-256", "hash": evidence_hash}
    ]
    payload["integrity_hash"] = evidence_hash

    html = _render_html(payload, result)
    return {
        "report_id": report_id,
        "investigation_id": investigation_id,
        "generated_at": generated_at,
        "integrity_hash": evidence_hash,
        "report": payload,
        "html": html,
    }


def _render_html(payload: dict[str, Any], result: dict[str, Any]) -> str:
    clusters = result.get("correlation", {}).get("clusters", [])
    cluster_rows = ""
    for c in clusters:
        refs = ", ".join(c.get("linked_account_refs", [])[:10])
        explain = "<br>".join(f"• {e}" for e in c.get("explainability", [])[:6])
        cluster_rows += f"""
        <tr>
          <td>{c.get('account_cluster_id', '')}</td>
          <td>{c.get('confidence_score', 0):.1f}%</td>
          <td>{refs}</td>
          <td>{explain}</td>
        </tr>"""

    tool_rows = ""
    for t in result.get("tool_results", []):
        status = "OK" if t.get("success") else "FAIL"
        tool_rows += f"<tr><td>{t.get('tool')}</td><td>{status}</td><td>{t.get('execution_time_ms', 0):.0f} ms</td></tr>"

    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>SOCMINT Report — {payload['query']}</title>
<style>
  body {{ font-family: 'Segoe UI', system-ui, sans-serif; margin: 40px; color: #1a1a2e; }}
  h1 {{ font-size: 1.4rem; border-bottom: 2px solid #1a1a2e; padding-bottom: 8px; }}
  .meta {{ color: #555; font-size: 0.85rem; margin-bottom: 24px; }}
  table {{ border-collapse: collapse; width: 100%; margin: 16px 0; font-size: 0.85rem; }}
  th, td {{ border: 1px solid #ccc; padding: 8px; text-align: left; vertical-align: top; }}
  th {{ background: #f0f0f5; }}
  .hash {{ font-family: monospace; font-size: 0.75rem; word-break: break-all; background: #f8f8fc; padding: 12px; }}
  .stamp {{ margin-top: 32px; font-size: 0.8rem; color: #666; }}
</style></head><body>
<h1>SOCMINT Investigation Report</h1>
<div class="meta">
  <strong>Classification:</strong> {payload['classification']}<br>
  <strong>Report ID:</strong> {payload['report_id']}<br>
  <strong>Investigation ID:</strong> {payload['investigation_id']}<br>
  <strong>Query:</strong> {payload['query']}<br>
  <strong>Generated:</strong> {payload['generated_at']}<br>
  <strong>Reviewer:</strong> {payload['reviewer']}
</div>

<h2>Tool Execution Log</h2>
<table><tr><th>Tool</th><th>Status</th><th>Duration</th></tr>{tool_rows}</table>

<h2>Identity Correlation Clusters</h2>
<table><tr><th>Cluster ID</th><th>Confidence</th><th>Linked Accounts</th><th>Explainability</th></tr>{cluster_rows}</table>

<h2>Evidence Integrity</h2>
<div class="hash"><strong>SHA-256 Integrity Hash:</strong><br>{payload['integrity_hash']}</div>

<div class="stamp">
  This report was generated by the SOCMINT Intelligence Platform. 
  Evidence hash enables chain-of-custody verification. Print to PDF for court submission.
</div>
</body></html>"""
